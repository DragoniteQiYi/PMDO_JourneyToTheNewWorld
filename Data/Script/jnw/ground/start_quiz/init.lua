      name = UI:ChoiceResult()
	end
	
	GAME:SetCharacterNickname(GAME:GetPlayerPartyMember(0), name)
    UI:ChoiceMenuYesNo(STRINGS:Format(STRINGS.MapStrings['Name_Confirm'], name), true)
    UI:WaitForChoice()
    ch = UI:ChoiceResult()
