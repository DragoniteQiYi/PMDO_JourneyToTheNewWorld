while not continue do
	if gender == 1 then
		UI:ChooseMonsterMenu(txt, starterListMale)
	elseif gender == 2 then
		UI:ChooseMonsterMenu(txt, starterListFemale)
	end	
	UI:WaitForChoice()	
	local result = UI:ChoiceResult()
	pkm = result
	
	for i = 1, #starterList do
		if starterList[i] == pkm then
			heroListNum = i
			break
		end
	end
	
	GAME:RemovePlayerTeam(0)
	GAME:WaitFrames(1)
	_DATA.Save.ActiveTeam.Players:Add(_DATA.Save.ActiveTeam:CreatePlayer(_DATA.Save.Rand, pkm, 5, "", 0))
	
	--add egg move
	if GAME:GetCharacterSkill(GAME:GetPlayerPartyMember(0), 3) ~= "" then 
		GAME:SetCharacterSkill(GAME:GetPlayerPartyMember(0), egg_move_list[pkm.Species], 3) -- override move in slot 4 if 4 moves are known
	else 
		GAME:LearnSkill(GAME:GetPlayerPartyMember(0), egg_move_list[pkm.Species])
	end
	
	COMMON.SetPlayerFromData(pkm)
	UI:ChoiceMenuYesNo(STRINGS:Format(STRINGS.MapStrings['Choice_Prompt'], _DATA:GetMonster(pkm.Species):GetColoredName()))
	UI:WaitForChoice()
	continue = UI:ChoiceResult()
	if not continue then
		GROUND:Hide("PLAYER")
	end
end
